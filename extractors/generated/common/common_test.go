// TestDetect_SentinelAllowlist exercises one fixture line per Sentinel
// entry; the closed allowlist must stay anchored to verbatim sample
// inputs so future edits to the regex set keep the allowlist
// auditable.
func TestDetect_SentinelAllowlist(t *testing.T) {
	cases := []struct {
		name string
		head string
		want string // expected SentinelGenerator
	}{
		{"protoc-gen-go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n", "protoc-gen-go"},
		{"protoc-gen-go-grpc", "// Code generated by protoc-gen-go-grpc. DO NOT EDIT.\n", "protoc-gen-go-grpc"},
		{"stringer", `// Code generated by "stringer -type=Color"; DO NOT EDIT.` + "\n", "stringer"},
		{"go-generate generic", "// Code generated by mygen DO NOT EDIT.\n", "go-generate"},
		{"openapi-generator", "// Generated by openapi-generator https://example\n", "openapi-generator"},
		{"ts-codegen", "// This file is auto-generated by graphql-codegen. DO NOT EDIT\n", "ts-codegen"},
		{"python-autogen", "# AUTOGENERATED -- do not edit\n", "python-autogen"},
		{"python-generated-by", "# Generated by my-codegen\n", "python-generated-by"},
		{"do-not-edit-hash", "# DO NOT EDIT. Generated by terraform-docs\n", "do-not-edit-hash"},
	}
	for _, tc := range cases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			res := Detect("unrelated_name.txt", []byte(tc.head))
			if res.SentinelGenerator != tc.want {
				t.Errorf("SentinelGenerator: got %q, want %q", res.SentinelGenerator, tc.want)
			}
			if !strings.Contains(res.MatchedSentinel, "DO NOT EDIT") &&
				!strings.Contains(res.MatchedSentinel, "AUTOGENERATED") &&
				!strings.Contains(res.MatchedSentinel, "Generated by") {
				t.Errorf("MatchedSentinel %q lacks the expected substring", res.MatchedSentinel)
			}
		})
	}
}

// TestDetect_FilenameAllowlist exercises the filename pattern closed
// list.
func TestDetect_FilenameAllowlist(t *testing.T) {
	cases := []struct {
		name string
		path string
		want string // expected FilenameGenerator (empty = no match)
	}{
		{"underscore-pb.go", "foo_pb.go", "protoc"},
		{"dot-pb.go", "foo.pb.go", "protoc"},
		{"gen.go", "foo.gen.go", "go-generate"},
		{"generated.ts", "client.generated.ts", "ts-codegen"},
		{"pb.gw.go", "api.pb.gw.go", "grpc-gateway"},
		{"bindings.gen.go", "bindings.gen.go", "abigen"},
		{"_string.go", "color_string.go", "stringer"},
		{"mock_ prefix", "mock_foo.go", "mockgen"},
		{"_mock.go suffix", "foo_mock.go", "mockgen"},
		{"unrelated", "regular.go", ""},
	}
	for _, tc := range cases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			res := Detect(tc.path, nil)
			if res.FilenameGenerator != tc.want {
				t.Errorf("FilenameGenerator: got %q, want %q", res.FilenameGenerator, tc.want)
			}
			if (tc.want != "") != res.MatchedFilename {
				t.Errorf("MatchedFilename: got %v, want %v", res.MatchedFilename, tc.want != "")
			}
		})
	}
}

// TestMatchesAnyGlob covers the path-vs-basename behaviour the
// manifest extractor relies on.
func TestMatchesAnyGlob(t *testing.T) {
	cases := []struct {
		name      string
		path      string
		globs     []string
		wantMatch bool
		wantGlob  string
	}{
		{"basename glob", "thing.gen.zig", []string{"*.gen.zig"}, true, "*.gen.zig"},
		{"path glob", "vendor/foo.go", []string{"vendor/*.go"}, true, "vendor/*.go"},
		{"path glob mismatch (nested)", "vendor/sub/foo.go", []string{"vendor/*.go"}, false, ""},
		{"exact match", "exact.py", []string{"exact.py"}, true, "exact.py"},
		{"backslash normalisation", "vendor\\foo.go", []string{"vendor/*.go"}, true, "vendor/*.go"},
		{"empty pattern skipped", "x.go", []string{"", "x.go"}, true, "x.go"},
		{"no match", "y.go", []string{"x.go"}, false, ""},
	}
	for _, tc := range cases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			got, glob := MatchesAnyGlob(tc.path, tc.globs)
			if got != tc.wantMatch {
				t.Errorf("matched: got %v, want %v", got, tc.wantMatch)
			}
			if glob != tc.wantGlob {
				t.Errorf("glob: got %q, want %q", glob, tc.wantGlob)
			}
		})
	}
}
