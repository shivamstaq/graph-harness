// fileChangedEvent builds a synthetic code.core.FileChanged event for
// the given relative path. The dispatcher would normally produce these.
func fileChangedEvent(t *testing.T, path string) kernel.Event {
	t.Helper()
	payload, err := json.Marshal(map[string]string{"path": path})
	if err != nil {
		t.Fatalf("marshal payload: %v", err)
	}
	return kernel.Event{
		Layer:   "code.core",
		Kind:    "FileChanged",
		Payload: payload,
	}
}

// newTestExtractor returns an Extractor that reads from testdata/
// rather than a synthetic workspace. We bypass the registry by
// constructing directly — the init() registration is tested in the
// dispatcher-side gate.
func newTestExtractor(t *testing.T) *Extractor {
	t.Helper()
	wd, err := os.Getwd()
	if err != nil {
		t.Fatalf("getwd: %v", err)
	}
	ext, err := New(cf.Deps{Workspace: filepath.Join(wd, "testdata"), Logf: t.Logf})
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	return ext.(*Extractor)
}

// TestHeuristicsExtractor walks the closed allowlist + escape-hatch
// cases against on-disk fixtures.
func TestHeuristicsExtractor(t *testing.T) {
	tests := []struct {
		name             string
		path             string
		wantEventKind    string // "" = expect no event
		wantGenerator    string
		wantConfidence   float64
		wantSentinelSub  string // substring that must appear in payload.sentinel
	}{
		{
			name:            "protoc-gen-go: sentinel + filename",
			path:            "foo.pb.go",
			wantEventKind:   "GeneratedArtifactAdded",
			wantGenerator:   "protoc-gen-go",
			wantConfidence:  0.99,
			wantSentinelSub: "protoc-gen-go",
		},
		{
			name:            "stringer: sentinel + filename",
			path:            "foo_string.go",
			wantEventKind:   "GeneratedArtifactAdded",
			wantGenerator:   "stringer",
			wantConfidence:  0.99,
			wantSentinelSub: "stringer",
		},
		{
			name:            "sentinel only (no filename match)",
			path:            "sentinel_only.go",
			wantEventKind:   "GeneratedArtifactAdded",
			wantGenerator:   "go-generate",
			wantConfidence:  0.85,
			wantSentinelSub: "DO NOT EDIT",
		},
		{
			name:           "filename only → UnverifiedGeneratedArtifact",
			path:           "mock_thing.go",
			wantEventKind:  "UnverifiedGeneratedArtifact",
			wantGenerator:  "mockgen", // suspected_generator
		},
		{
			name:          "neither: no emission",
			path:          "regular.go",
			wantEventKind: "",
		},
		{
			name:            "openapi-generator TS sentinel",
			path:            "openapi.ts",
			wantEventKind:   "GeneratedArtifactAdded",
			wantGenerator:   "openapi-generator",
			wantConfidence:  0.85,
			wantSentinelSub: "openapi-generator",
		},
		{
			name:            "python AUTOGENERATED sentinel",
			path:            "autogen.py",
			wantEventKind:   "GeneratedArtifactAdded",
			wantGenerator:   "python-autogen",
			wantConfidence:  0.85,
			wantSentinelSub: "AUTOGENERATED",
		},
		{
			name:            "grpc-gateway sentinel + filename",
			path:            "api.pb.gw.go",
			wantEventKind:   "GeneratedArtifactAdded",
			wantGenerator:   "go-generate", // generic-sentinel wins on label tie; filename was grpc-gateway
			wantConfidence:  0.99,
			wantSentinelSub: "DO NOT EDIT",
		},
	}

	for _, tc := range tests {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			ext := newTestExtractor(t)
			ev := fileChangedEvent(t, tc.path)

			out, err := ext.OnEvent(context.Background(), ev)
			if err != nil {
				t.Fatalf("OnEvent: %v", err)
			}

			if tc.wantEventKind == "" {
				if len(out) != 0 {
					t.Fatalf("expected zero events, got %d (%+v)", len(out), out)
				}
				return
			}

			if len(out) != 1 {
				t.Fatalf("expected 1 event, got %d (%+v)", len(out), out)
			}
			got := out[0]
			if got.Layer != "code.framework" {
				t.Errorf("Layer: got %q, want %q", got.Layer, "code.framework")
			}
			if got.Kind != tc.wantEventKind {
				t.Errorf("Kind: got %q, want %q", got.Kind, tc.wantEventKind)
			}

			// Decode payload generically and assert the fields we
			// care about.
			var pl map[string]any
			if err := json.Unmarshal(got.Payload, &pl); err != nil {
				t.Fatalf("unmarshal payload: %v", err)
			}

			if tc.wantEventKind == "GeneratedArtifactAdded" {
				if gen, _ := pl["generator"].(string); gen != tc.wantGenerator {
					t.Errorf("generator: got %q, want %q", gen, tc.wantGenerator)
				}
				if got.Subject == nil {
					t.Errorf("Subject is nil for GeneratedArtifactAdded")
				}
				if path, _ := pl["path"].(string); path != tc.path {
					t.Errorf("path: got %q, want %q", path, tc.path)
				}
				// Confidence lives under provenance.confidence.
				prov, _ := pl["provenance"].(map[string]any)
				if prov == nil {
					t.Fatalf("provenance missing in payload")
				}
				if conf, _ := prov["confidence"].(float64); conf != tc.wantConfidence {
					t.Errorf("confidence: got %v, want %v", conf, tc.wantConfidence)
				}
				if tc.wantSentinelSub != "" {
					sent, _ := pl["sentinel"].(string)
					if !containsSubstr(sent, tc.wantSentinelSub) {
						t.Errorf("sentinel %q does not contain %q", sent, tc.wantSentinelSub)
					}
				}
			} else if tc.wantEventKind == "UnverifiedGeneratedArtifact" {
				if gen, _ := pl["suspected_generator"].(string); gen != tc.wantGenerator {
					t.Errorf("suspected_generator: got %q, want %q", gen, tc.wantGenerator)
				}
				if path, _ := pl["path"].(string); path != tc.path {
					t.Errorf("path: got %q, want %q", path, tc.path)
				}
			}
		})
	}
}

// TestHeuristicsMissingPayload covers the malformed/empty FileChanged
// payload path — should be a no-op, not a crash.
func TestHeuristicsMissingPayload(t *testing.T) {
	ext := newTestExtractor(t)
	out, err := ext.OnEvent(context.Background(), kernel.Event{
		Layer: "code.core", Kind: "FileChanged",
		Payload: json.RawMessage(`{}`),
	})
	if err != nil {
		t.Fatalf("OnEvent: %v", err)
	}
	if len(out) != 0 {
		t.Fatalf("expected zero events, got %d", len(out))
	}
}

// TestHeuristicsMissingFile covers the path where the file vanished
// between FileChanged and our read. Should be a no-op for files that
// also don't match a filename pattern, and Unverified for ones that
// do (filename pattern is independent of file contents).
func TestHeuristicsMissingFile(t *testing.T) {
	ext := newTestExtractor(t)
	// "vanished.go" doesn't exist; doesn't match any filename pattern.
	out, err := ext.OnEvent(context.Background(), fileChangedEvent(t, "does-not-exist.go"))
	if err != nil {
		t.Fatalf("OnEvent: %v", err)
	}
	if len(out) != 0 {
		t.Fatalf("expected zero events for missing non-pattern file, got %d", len(out))
	}

	// "missing_mock.go" matches mock_*.go via prefix... wait, no — it's
	// "missing_mock.go" not "mock_missing.go". Use mock_missing.go.
	out, err = ext.OnEvent(context.Background(), fileChangedEvent(t, "mock_missing.go"))
	if err != nil {
		t.Fatalf("OnEvent: %v", err)
	}
	if len(out) != 1 {
		t.Fatalf("expected 1 Unverified event for missing pattern-match, got %d", len(out))
	}
	if out[0].Kind != "UnverifiedGeneratedArtifact" {
		t.Errorf("Kind: got %q, want UnverifiedGeneratedArtifact", out[0].Kind)
	}
}

// TestHeuristicsRegistered verifies the package-level init() side
// effect.
func TestHeuristicsRegistered(t *testing.T) {
	ctor, desc, ok := cf.Lookup(Name)
	if !ok {
		t.Fatalf("extractor %q not registered", Name)
	}
	if ctor == nil {
		t.Fatalf("constructor nil")
	}
	if desc.Family != "generated" {
		t.Errorf("Family: got %q, want %q", desc.Family, "generated")
	}
	if len(desc.Outputs) != 1 || desc.Outputs[0] != cf.KindGeneratedArtifact {
		t.Errorf("Outputs: got %v, want [%s]", desc.Outputs, cf.KindGeneratedArtifact)
	}
}

func containsSubstr(s, sub string) bool {
	if sub == "" {
		return true
	}
	for i := 0; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return true
		}
	}
	return false
}
